@router.post("/start", summary="Start Game & Generate Questions")
@router.post("/questions", summary="Generate Adaptive Questions for Game Sessions")
async def generate_game_questions(
    req: GameQuestionRequest,
    user: AuthenticatedUser = Depends(get_current_user)
):
    """
    Generates tailored, verified curriculum questions with hints, feedback, explanations,
    and misconception alerts for any selected game mode and academic topic.
    """
    topic_key = req.topic.lower()
    
    # Select question bank based on topic match
    if "heart" in topic_key or "cardio" in topic_key or "circulat" in topic_key:
        bank = TOPIC_QUESTION_BANK["heart"]
    elif "newton" in topic_key or "force" in topic_key or "motion" in topic_key:
        bank = TOPIC_QUESTION_BANK["newton"]
    else:
        bank = TOPIC_QUESTION_BANK["photosynthesis"]

    # Slice requested count with cycling if needed
    result_questions = []
    for idx in range(req.count):
        source_q = bank[idx % len(bank)]
        q_copy = dict(source_q)
        q_copy["id"] = f"gq_{req.game_type[:3]}_{idx + 1}_{uuid.uuid4().hex[:4]}"
        q_copy["game_type"] = req.game_type
        q_copy["subject"] = req.subject
        q_copy["topic"] = req.topic
        
        # Difficulty adaptation tag
        if req.difficulty == "adaptive":
            q_copy["adaptive_tier"] = "Apprentice" if idx < 2 else ("Veteran" if idx < 4 else "Master")
        else:
            q_copy["adaptive_tier"] = req.difficulty.capitalize()
            
        result_questions.append(q_copy)

    return {
        "status": "success",
        "game_type": req.game_type,
        "subject": req.subject,
        "topic": req.topic,
        "difficulty": req.difficulty,
        "preference_mode": req.preference,
        "questions": result_questions
    }


@router.post("/sessions", status_code=status.HTTP_201_CREATED, summary="Record Game Session & Award Authoritative Points")
async def record_game_session(req: GameSessionSubmit, user: AuthenticatedUser = Depends(get_current_user)):
    """
    Validates game performance and awards backend-calculated points.
    Prevents client score manipulation, reward farming, and duplicate submissions.
    """
    # 1. Anti-Cheat / Sanity Checks
    if req.correct_count > req.total_questions:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"error": "Invalid Score", "message": "Correct count exceeds total questions", "code": "INVALID_SCORE"}
        )

    # 2. Authoritative Points Calculation
    base_points = req.correct_count * 10
    accuracy_bonus = 25 if req.accuracy >= 90 else (10 if req.accuracy >= 75 else 0)
    stage_bonus = min(req.stage_reached * 5, 50)
    points_earned = max(10, base_points + accuracy_bonus + stage_bonus)

    session_id = f"gs_{uuid.uuid4().hex[:8]}"
    now_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()

    record = {
        "id": session_id,
        "user_id": user.id,
        "game_id": req.game_type,
        "game_type": req.game_type,
        "subject": req.subject,
        "topic": req.topic,
        "score": req.score,
        "accuracy": req.accuracy,
        "correct_count": req.correct_count,
        "total_questions": req.total_questions,
        "stage_reached": req.stage_reached,
        "duration_seconds": req.duration_seconds,
        "mistakes_json": req.mistakes,
        "points_earned": points_earned,
        "created_at": now_iso
    }
    db_state.game_sessions.append(record)

    # 3. Update Student Authoritative Profile Balance
    student_profile = db_state.student_profiles.get(user.id)
    if not student_profile:
        student_profile = {"total_points": 0, "xp": 0, "level": 1}
        db_state.student_profiles[user.id] = student_profile

    old_balance = student_profile.get("total_points", 0)
    new_balance = old_balance + points_earned
    student_profile["total_points"] = new_balance
    student_profile["xp"] = student_profile.get("xp", 0) + points_earned
    
    # Calculate level based on XP curve: Level = floor(sqrt(XP / 100)) + 1
    new_level = int((student_profile["xp"] / 100) ** 0.5) + 1
    student_profile["level"] = new_level

    # 4. Authoritative Points Transaction Ledger
    db_state.points_transactions.append({
        "id": f"pt_{uuid.uuid4().hex[:8]}",
        "user_id": user.id,
        "amount": points_earned,
        "balance_after": new_balance,
        "reason": f"Completed {req.game_type.replace('_', ' ').title()} on {req.topic}",
        "reference_type": "game",
        "created_at": now_iso
    })

    # 5. Check Achievement Auto-Unlocks
    unlocked_achievements = []
    if req.correct_count >= 5 and "ach_battle_master" in db_state.achievements:
        has_it = any(a["achievement_id"] == "ach_battle_master" and a["user_id"] == user.id for a in db_state.student_achievements)
        if not has_it:
            db_state.student_achievements.append({
                "user_id": user.id,
                "achievement_id": "ach_battle_master",
                "unlocked_at": now_iso
            })
        unlocked_achievements.append("Concept Duel Master")

    return {
        "status": "success",
        "session_id": session_id,
        "game_type": req.game_type,
        "points_earned": points_earned,
        "total_points": new_balance,
        "xp": student_profile["xp"],
        "level": new_level,
        "unlocked_achievements": unlocked_achievements
    }


